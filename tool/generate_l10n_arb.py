DESC_SUFFIX_EN = " screen."
DESC_PREFIX_AR = "شاشة "


def main() -> None:
    import os

    root = os.path.join(os.path.dirname(__file__), "..", "lib", "l10n")
    existing_en_path = os.path.join(root, "app_en.arb")
    existing_ar_path = os.path.join(root, "app_ar.arb")
    with open(existing_en_path, encoding="utf-8") as f:
        en = json.load(f)
    with open(existing_ar_path, encoding="utf-8") as f:
        ar = json.load(f)

    en.update({**BASE_EN, **SCREENS_EN})
    ar.update({**BASE_AR, **SCREENS_AR})
    for k, v in SCREENS_EN.items():
        en[f"{k}Desc"] = v + DESC_SUFFIX_EN
    for k, v in SCREENS_AR.items():
        ar[f"{k}Desc"] = DESC_PREFIX_AR + v + "."

    with open(os.path.join(root, "app_en.arb"), "w", encoding="utf-8") as f:
        json.dump(en, f, ensure_ascii=False, indent=2)
        f.write("\n")
    with open(os.path.join(root, "app_ar.arb"), "w", encoding="utf-8") as f:
        json.dump(ar, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("wrote arb files", len(en), "keys")


if __name__ == "__main__":
    main()
